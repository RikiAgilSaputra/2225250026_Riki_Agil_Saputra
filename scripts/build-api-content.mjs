// Bundles content/ (the source of truth) into the Supabase Edge Function as a TS module.
// Run automatically by `npm run api:test`, `api:dev` and `api:deploy`. Output is generated, not committed.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const contentDir = join(root, "content");
const modulesDir = join(contentDir, "modules");

const files = readdirSync(modulesDir).filter((f) => f.endsWith(".json")).sort();
const moduleFiles = files.map((f) => JSON.parse(readFileSync(join(modulesDir, f), "utf8")));
let path = null;
try {
  path = JSON.parse(readFileSync(join(contentDir, "path.json"), "utf8"));
} catch {
  path = null;
}

const out = `// GENERATED by scripts/build-api-content.mjs from content/. Do not edit.
export const moduleFiles: unknown[][] = ${JSON.stringify(moduleFiles)};
export const learningPath: unknown = ${JSON.stringify(path)};
`;
writeFileSync(join(root, "supabase", "functions", "api", "content.gen.ts"), out);
console.log(`content.gen.ts: ${files.length} module files${path ? " + path.json" : ""}`);
